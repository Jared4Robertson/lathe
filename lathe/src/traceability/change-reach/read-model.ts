// The Change reach read model (LA-TRC-RM14), shaped for the reach of a change (LA-TRC-UC24): given the records the Owner
// or an Agent means to change, every record the change would touch, each once, grouped by stage, with the changed
// records it is reached from and the shortest path of links that reaches it; the files those records name; the tests
// among them with their states; and the use cases, journeys and business outcomes they serve.
//
// A record depends on another, and is reached from it, when it
// - sits under a changed record (every descendant of a changed record is touched);
// - names it through a link that makes it depend on what it names (fulfills, invokes, presents, renders, builds, meets,
//   fills, carries out, persists, stores, hears, is fed by, reads, calls, checks, selects by, raises, exchanges with,
//   starts from, provided by, has, about, builds on), or is generated by it;
// - names it in a column of its own or of one of its parts (a step's interface, an entity field's value object);
// - builds it or proves it, as its chain says (the checks' run: an obligation's technical records and tests); or
// - sits under a record it reached and is not an obligation itself (a command's handler and endpoint, a query's CLI
//   query), since those carry out what they sit under.
// It never follows a link upward to the purpose a record serves (serves, measured by, follows, offers): those are
// named apart, as its purposes, by the Serves reach (LA-TRC-DS06). The chains are the checks' run's (`ReadView.checked`);
// the rest is the rows'. The projection is the only code that reads them for the query and the only code that writes
// the read model's table; the query handler reads it only through the reader.
import type { ReadView } from '../../platform/data/rules.ts';
import type { Stage } from '../../platform/data/schema.ts';
import { placementOf, type Placed } from '../../exploring/placement.ts';
import { compareIds } from '../../platform/data/ids.ts';
import { servesOf } from '../../trace/serves.ts';

/** One link of a path: the record reached, and the words that join it to the record before it, read from its end. */
export interface ReachHop {
  id: string;
  /** Such as "Fulfills", "Sits under", "Builds" or "Proves"; null for the changed record the path starts from. */
  via: string | null;
}

/** One record the change touches. */
export interface ReachRecord {
  id: string;
  kind: string;
  /** The changed records it is reached from, in the order they were named. */
  from: string[];
  /** The shortest path of links that reaches it, from the first changed record that does: that record first, it last. */
  path: ReachHop[];
  /** The file it names, for a technical record or a test; null otherwise. */
  file: string | null;
  /** Its state, for a test; null otherwise. */
  state: string | null;
}

/** The records of one stage the change touches, in kind order, then by ID. */
export interface ReachGroup {
  /** The stage; null for the records outside the stages (an open question). */
  stage: Stage | null;
  label: string;
  records: ReachRecord[];
}

/** The reach of a change. */
export interface ChangeReach {
  /** The records to change, in the order they were named. */
  changed: string[];
  /** How many records the change touches, the changed records left out. */
  count: number;
  /** The records it touches, by stage in the stages' order; a stage it touches nothing in is left out. */
  groups: ReachGroup[];
  /** The files the changed and touched records name (technical records and tests), each with those records, by path. */
  files: { path: string; records: string[] }[];
  /** The use cases, journeys and business outcomes the changed and touched records serve, each in ID order. */
  purposes: { useCases: string[]; journeys: string[]; outcomes: string[] };
}

/** The read model's table, kept in memory: the reach of any change, worked out when it is asked for. */
export interface ChangeReachTable {
  /** The records among the IDs that the data does not hold. */
  missing(ids: readonly string[]): string[];
  reachOf(ids: readonly string[]): ChangeReach;
}

/** Links that point up to a record's purpose or its context, never to what it depends on: the reach does not follow them. */
const UPWARD = new Set(['serves', 'measured_by', 'follows', 'offers']);
/** Links whose target depends on their source (the tooling record writes the generated record). */
const FORWARD = new Set(['generates']);

const SITS_UNDER = 'Sits under';
const str = (value: unknown) => (typeof value === 'string' ? value : '');
const words = (column: string) => column.replace(/_id$/, '').replaceAll('_', ' ');

/** The projection: the read model's table over the rows and the checks' run (in memory; nothing keeps it). */
export function changeReachTableFrom(view: ReadView): ChangeReachTable {
  const { schema } = view;
  let placed: ReadonlyMap<string, Placed> | null = null;
  // Each record's dependents: the records that depend on it, each with the words read from the dependent's end.
  let dependents: Map<string, ReachHop[]> | null = null;
  let children: Map<string, string[]> | null = null;
  let served: ReturnType<typeof servesOf> | null = null;

  const kindRank = new Map(Object.keys(schema.kinds).map((k, i) => [k, schema.kinds[k].position ?? 1000 + i]));
  const stageRank = new Map(schema.stages.map((s) => [s.name, s.position]));
  const load = () => {
    if (placed) return;
    placed = placementOf(view);
    const deps = new Map<string, ReachHop[]>();
    const kids = new Map<string, string[]>();
    const add = (on: string, id: string, via: string) => {
      if (on === id || !placed!.has(on) || !placed!.has(id)) return;
      const list = deps.get(on);
      if (list) list.push({ id, via });
      else deps.set(on, [{ id, via }]);
    };
    for (const r of placed.values()) if (r.parent) kids.set(r.parent, [...(kids.get(r.parent) ?? []), r.id]);
    // Links: the source names the target, and depends on it, unless the link points up to a purpose.
    for (const relation of Object.values(schema.relations)) {
      if (UPWARD.has(relation.name) || !schema.tables[relation.name]) continue;
      for (const row of view.rows(relation.name)) {
        const [source, target] = [str(row.source_id), str(row.target_id)];
        if (FORWARD.has(relation.name)) add(source, target, relation.reverseLabel);
        else add(target, source, relation.forwardLabel);
      }
    }
    // Columns: a record names another in a column that is not its parent's, or one of its parts does.
    for (const table of Object.values(schema.tables)) {
      const kind = schema.kinds[table.name];
      if (!(kind || (table.role === 'part' && table.ownerColumn))) continue;
      const skip = new Set(['id', ...(kind?.parents.map((p) => p.column) ?? []), ...(table.ownerColumn ? [table.ownerColumn] : [])]);
      const columns = table.foreignKeys.filter((f) => f.columns.length === 1 && !skip.has(f.columns[0])).map((f) => f.columns[0]);
      if (columns.length === 0) continue;
      for (const row of view.rows(table.name)) {
        const self = kind ? str(row.id) : str(row[table.ownerColumn!]);
        for (const column of columns) {
          const named = str(row[column]);
          if (named) add(named, self, `Names in its ${words(column)}`);
        }
      }
    }
    // Chains: an obligation's technical records build it, and its tests prove it. A provider the chain counts as its
    // build (an integration) is not built from it, so the reach does not follow it.
    const technical = (id: string) => schema.kinds[placed!.get(id)?.kind ?? '']?.stage === 'technical-specification';
    for (const chain of view.checked?.chains ?? []) {
      for (const id of chain.build) if (technical(id)) add(chain.obligation, id, 'Builds');
      for (const id of chain.tests) add(chain.obligation, id, 'Proves');
    }
    dependents = deps;
    children = kids;
  };

  /** The records a change of one record touches, each with the path that reaches it first (breadth first). */
  const walk = (start: string): Map<string, ReachHop[]> => {
    const paths = new Map<string, ReachHop[]>([[start, [{ id: start, via: null }]]]);
    const queue = [start];
    const descendant = new Set<string>([start]);
    for (let i = 0; i < queue.length; i++) {
      const at = queue[i];
      const path = paths.get(at)!;
      const visit = (id: string, via: string) => {
        if (paths.has(id)) return;
        paths.set(id, [...path, { id, via }]);
        queue.push(id);
      };
      for (const child of children!.get(at) ?? []) {
        // Under a changed record, everything; under a record reached otherwise, only what carries it out.
        if (descendant.has(at)) descendant.add(child);
        else if (schema.kinds[placed!.get(child)!.kind]?.obligation) continue;
        visit(child, SITS_UNDER);
      }
      for (const d of dependents!.get(at) ?? []) visit(d.id, d.via ?? '');
    }
    paths.delete(start);
    return paths;
  };

  return {
    missing(ids) {
      load();
      return ids.filter((id) => !placed!.has(id));
    },
    reachOf(ids) {
      load();
      const changed = [...new Set(ids)];
      const reached = new Map<string, { from: string[]; path: ReachHop[] }>();
      for (const start of changed) {
        for (const [id, path] of walk(start)) {
          if (changed.includes(id)) continue;
          const seen = reached.get(id);
          if (!seen) reached.set(id, { from: [start], path });
          else {
            seen.from.push(start);
            if (path.length < seen.path.length) seen.path = path;
          }
        }
      }
      const recordOf = (id: string): ReachRecord => {
        const r = placed!.get(id)!;
        const isTest = schema.kinds[r.kind]?.stage === 'test-plan' && !!schema.tables[r.kind]?.columns.some((c) => c.name === 'state');
        return { id, kind: r.kind, from: reached.get(id)!.from, path: reached.get(id)!.path, file: str(r.row.file).trim() || null, state: isTest ? str(r.row.state) || null : null };
      };
      const byStage = new Map<Stage | null, ReachRecord[]>();
      for (const id of reached.keys()) {
        const record = recordOf(id);
        const stage = schema.kinds[record.kind]?.stage ?? null;
        byStage.set(stage, [...(byStage.get(stage) ?? []), record]);
      }
      const groups: ReachGroup[] = [...byStage]
        .sort(([a], [b]) => (a === null ? 1 : b === null ? -1 : stageRank.get(a)! - stageRank.get(b)!))
        .map(([stage, records]) => ({
          stage,
          label: stage === null ? 'Outside the stages' : schema.stages.find((s) => s.name === stage)!.label,
          records: records.sort((a, b) => kindRank.get(a.kind)! - kindRank.get(b.kind)! || compareIds(a.id, b.id)),
        }));
      const touched = [...changed, ...reached.keys()];
      const files = new Map<string, string[]>();
      for (const id of touched) {
        const file = str(placed!.get(id)!.row.file).trim();
        if (file) files.set(file, [...(files.get(file) ?? []), id]);
      }
      served ??= servesOf(view);
      const purposes = { useCases: new Set<string>(), journeys: new Set<string>(), outcomes: new Set<string>() };
      for (const id of touched) {
        const s = served.get(id);
        if (!s) continue;
        for (const u of s.useCases) purposes.useCases.add(u);
        for (const j of s.journeys) purposes.journeys.add(j);
        for (const o of s.outcomes) purposes.outcomes.add(o);
      }
      const sorted = (set: Set<string>) => [...set].sort(compareIds);
      return {
        changed,
        count: reached.size,
        groups,
        files: [...files].sort(([a], [b]) => a.localeCompare(b)).map(([path, records]) => ({ path, records: records.sort(compareIds) })),
        purposes: { useCases: sorted(purposes.useCases), journeys: sorted(purposes.journeys), outcomes: sorted(purposes.outcomes) },
      };
    },
  };
}
